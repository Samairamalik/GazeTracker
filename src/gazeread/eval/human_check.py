"""Human check (spec 7.4), single reader: paragraph attention vs comprehension answers.

    python -m gazeread.eval.human_check [sessions/<id> ...]      # `make human-check`

With no arguments, uses every camera session in sessions/ that contains quiz answers. Each
session = one passage: its latest reading is analysed with the app's own analyze_session, and
each paragraph's dwell is joined with the answers to the questions about that paragraph.
Writes results/tables/m6_paragraphs.csv, m6_passages.csv and results/m6_summary.md.
Single reader, illustrative only: no statistical test is attempted.
"""
import csv
import sys
from pathlib import Path

import numpy as np
import yaml

from gazeread.analysis.heatmap import analyze_session
from gazeread.app.session import read_events

ROOT = Path(__file__).resolve().parents[3]
LABEL = "single reader, illustrative only"
MIN_PAGE_S = 2.0   # a page on screen for less than this was skipped (e.g. a double key press): its paragraphs are excluded


def session_tables(events: list[dict], cfg: dict, session: str) -> tuple[dict, list[dict]]:
    """(passage row, paragraph rows) for one session."""
    res = analyze_session(events, cfg)
    p0 = [i for i, e in enumerate(events) if e["type"] == "page" and e["page"] == 0][-1]
    meta = [e for e in events[:p0] if e["type"] == "meta"][-1]
    shown = {ln["para_id"]: pg["t_off"] - pg["t_on"] for pg in res["pages"] for ln in pg["lines"]}
    end = res["pages"][-1]["t_off"]
    answers = [e for e in events if e["type"] == "answer" and e["t"] >= end]
    lines = [ln for pg in res["pages"] for ln in pg["lines"]]
    paras = sorted({ln["para_id"] for ln in lines})
    dw = {}
    for src in ("fixations", "samples"):
        line_s = np.concatenate([pg["dwell"][src]["line_s"] for pg in res["pages"]])
        ids = np.array([ln["para_id"] for ln in lines])
        s = np.array([line_s[ids == p].sum() for p in paras])
        dw[src] = (s, s / s.sum() if s.sum() > 0 else np.zeros_like(s))
    rows = []
    for i, p in enumerate(paras):
        a = [x for x in answers if x["para_id"] == p]
        rows.append({"session": session, "passage": meta.get("text"), "skim": int(bool(meta.get("skim"))),
                     "para_id": p, "dwell_s_fix": round(float(dw["fixations"][0][i]), 2),
                     "dwell_frac_fix": round(float(dw["fixations"][1][i]), 3),
                     "dwell_s_samples": round(float(dw["samples"][0][i]), 2),
                     "dwell_frac_samples": round(float(dw["samples"][1][i]), 3),
                     "n_questions": len(a), "n_correct": sum(bool(x["correct"]) for x in a),
                     "page_shown_s": round(shown[p], 1), "page_not_shown": int(shown[p] < MIN_PAGE_S)})
    passage = {"session": session, "passage": meta.get("text"), "skim": int(bool(meta.get("skim"))),
               "source": meta.get("source"), "sigma_px": res["sigma_px"], "rms_y": res["rms_y"],
               "granularity": res["granularity"],
               "reading_s": round(res["pages"][-1]["t_off"] - res["pages"][0]["t_on"], 1),
               "n_questions": len(answers), "n_correct": sum(bool(x["correct"]) for x in answers)}
    return passage, rows


def find_sessions(root: Path) -> list[Path]:
    out = []
    for f in sorted((root / "sessions").glob("*/events.jsonl")):
        ev = read_events(f)
        meta = [e for e in ev if e["type"] == "meta"]
        if meta and meta[-1].get("source") == "camera" and any(e["type"] == "answer" for e in ev):
            out.append(f.parent)
    return out


def write_csv(path: Path, rows: list[dict]) -> None:
    with path.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)


def summary_md(passages: list[dict], paras: list[dict]) -> str:
    synthetic = any(p["source"] != "camera" for p in passages)
    L = [f"# M6 human check ({LABEL})", ""] + (
        ["**SYNTHETIC SESSIONS INCLUDED: not a measurement.**", ""] if synthetic else []) + [
         "Generated by `make human-check`; do not edit by hand. One reader; each passage read in its own "
         "session after a fresh calibration; questions answered right after reading. Dwell = gaze time "
         "credited to each paragraph by the app's analysis (soft mapping); fractions are within a passage.", "",
         "## Passages", "", "| passage | condition | σ px | σ_y px | granularity | reading time s | correct |",
         "|---|---|---|---|---|---|---|"]
    for p in passages:
        L.append(f"| {p['passage']} | {'skimmed' if p['skim'] else 'read'} | {p['sigma_px']:.0f} | {p['rms_y']:.0f} | "
                 f"{p['granularity']} | {p['reading_s']} | {p['n_correct']}/{p['n_questions']} |")
    L += ["", "## Paragraphs", "", "| passage | condition | paragraph | dwell s (fixations) | dwell share | "
          "dwell share (samples) | questions correct | note |", "|---|---|---|---|---|---|---|---|"]
    for r in paras:
        L.append(f"| {r['passage']} | {'skimmed' if r['skim'] else 'read'} | {r['para_id']} | {r['dwell_s_fix']} | "
                 f"{r['dwell_frac_fix']:.2f} | {r['dwell_frac_samples']:.2f} | {r['n_correct']}/{r['n_questions']} |"
                 + (f" **page shown {r['page_shown_s']} s: not read** |" if r["page_not_shown"] else " |"))

    def group(rows, name):
        if not rows:
            return f"| {name} | 0 | – | – | – |"
        return (f"| {name} | {len(rows)} | {np.mean([r['dwell_frac_fix'] for r in rows]):.2f} | "
                f"{np.mean([r['dwell_frac_samples'] for r in rows]):.2f} | "
                f"{np.mean([r['dwell_s_fix'] for r in rows]):.1f} |")
    asked = [r for r in paras if r["n_questions"] and not r["page_not_shown"]]
    skipped = [r for r in paras if r["page_not_shown"]]
    if skipped:
        L += ["", f"Excluded below: {len(skipped)} paragraph(s) whose page was on screen for less than {MIN_PAGE_S:g} s "
              "(" + ", ".join(f"{r['passage']} paragraph {r['para_id']}" for r in skipped) + "); they were never "
              "read, so their dwell and answers say nothing about attention. The reader had already seen those "
              "questions, so the passage could not be re-run without bias."]
    L += ["", "## Paragraphs grouped by answers (excluding paragraphs that were not shown)", "",
          "| group | paragraphs | mean dwell share (fixations) | mean dwell share (samples) | mean dwell s |",
          "|---|---|---|---|---|",
          group([r for r in asked if r["n_correct"] == r["n_questions"]], "all questions correct"),
          group([r for r in asked if r["n_correct"] < r["n_questions"]], "at least one missed"),
          "", "## Skimmed vs read passages", "",
          "| condition | passages | reading time s | correct (paragraphs that were shown) |", "|---|---|---|---|"]
    for cond, flag in (("read", 0), ("skimmed", 1)):
        ps = [p for p in passages if p["skim"] == flag]
        rs = [r for r in paras if r["skim"] == flag and not r["page_not_shown"]]
        if ps:
            L.append(f"| {cond} | {len(ps)} | {np.mean([p['reading_s'] for p in ps]):.1f} | "
                     f"{sum(r['n_correct'] for r in rs)}/{sum(r['n_questions'] for r in rs)} |")
    L += ["", f"**{LABEL.capitalize()}:** one person, three passages and a dozen questions. These tables show "
          "whether the heatmap and the answers point the same way for this reader; they do not support "
          "general claims. Dwell shares within a passage depend on paragraph length and on the gaze error "
          "of that session (σ above).", ""]
    return "\n".join(L)


def main() -> None:
    cfg = yaml.safe_load((ROOT / "configs/default.yaml").read_text())["analysis"]
    sessions = [Path(a) for a in sys.argv[1:]] or find_sessions(ROOT)
    if not sessions:
        sys.exit("No sessions with quiz answers found (run `make app TEXT=alice_passage1` and answer the questions).")
    passages, paras = [], []
    for s in sessions:
        p, rows = session_tables(read_events(s / "events.jsonl"), cfg, s.name)
        passages.append(p)
        paras += rows
    (ROOT / "results" / "tables").mkdir(parents=True, exist_ok=True)
    write_csv(ROOT / "results" / "tables" / "m6_passages.csv", passages)
    write_csv(ROOT / "results" / "tables" / "m6_paragraphs.csv", paras)
    (ROOT / "results" / "m6_summary.md").write_text(summary_md(passages, paras), encoding="utf-8")
    print(f"{len(sessions)} sessions -> results/m6_summary.md ({LABEL})")


if __name__ == "__main__":
    main()
